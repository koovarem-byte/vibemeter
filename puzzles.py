# уровни (19.11, отзывы беты): start — 14–17 лет (школа, друзья, первая переписка),
# pro — отношения, бывшие, ссоры, деньги. У новых задач уровень прописан, у старых — здесь.
_PRO = {1, 8, 12, 22, 23, 24, 25, 26, 28, 31, 32, 33, 34}
for _i, _p in enumerate(PUZZLES):
    _p.setdefault("level", "pro" if _i in _PRO else "start")
LEVELS = ("start", "pro")


def ids(level: str | None = None) -> list[int]:
    return [i for i, p in enumerate(PUZZLES) if level is None or p["level"] == level]


def today_index(level: str | None = None) -> int:
    """Задача дня: одна на всех своего уровня (без уровня — из всех задач, для ссылок другу)."""
    own = ids(level if level in LEVELS else None)
    return own[datetime.now(MSK).date().toordinal() % len(own)]


def user_level(user) -> str:
    lvl = user.get("level") if user else None
    return lvl if lvl in LEVELS else "start"


def pool(level: str) -> list[int]:
    """Задачи уровня по порядку: сначала задача дня и дальше по кругу; «Опытному» после своих — школьные.
    «Начинаю» видит только start (14–17 лет: без бывших, денег и ссор в отношениях)."""
    own = ids(level)
    k = own.index(today_index(level))
    order = own[k:] + own[:k]
    if level == "pro":
        order += ids("start")
    return order


RANKS = [(1400, "Гроссмейстер"), (1000, "Ферзь"), (700, "Ладья"), (400, "Слон"), (200, "Конь")]


def rank(rating: int) -> str:
    """Звания по Эло (rating.py): 0 Пешка, 200 Конь, 400 Слон, 700 Ладья, 1000 Ферзь, 1400 Гроссмейстер."""
    for limit, name in RANKS:
        if rating >= limit:
            return name
    return "Пешка"


def next_rank(rating: int):
    """(порог, звание) следующего звания или None."""
    for limit, name in reversed(RANKS):
        if rating < limit:
            return limit, name
    return None


# очки за ход партии с ИИ (# — мат в твою пользу)
MOVE_POINTS = {"!!": 15, "!": 8, "?": -3, "??": -5, "#": 20}


def stars(difficulty: int) -> int:
    """Сложность ситуации 1000–2200 -> 1–5 звёзд."""
    return max(1, min(5, (difficulty - 1000) // 250 + 1))


def game_points(badges: list[str], result: str, difficulty: int) -> int:
    """Очки за партию: сумма ходов + бонус за победу (больше за сложную) или −5 за мат."""
    pts = sum(MOVE_POINTS.get(b, 0) for b in badges)
    if result == "win":
        pts += 5 * stars(difficulty)
    elif result == "mate":
        pts -= 5
    return pts


def move_order(puzzle_id: int) -> list[int]:
    """Порядок кнопок: свой для каждой задачи, чтобы лучший ход не стоял на одном месте."""
    import random
    order = list(range(len(PUZZLES[puzzle_id]["moves"])))
    random.Random(puzzle_id * 7919 + 13).shuffle(order)
    return order
