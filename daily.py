"""Вайб дня: один вопрос «а/б» на всех, меняется каждый день по Москве."""

from datetime import datetime
from zoneinfo import ZoneInfo

DAILY = [
    ("Утро или ночь?", "Утро", "Ночь"),
    ("Горы или море?", "Горы", "Море"),
    ("Кофе или чай?", "Кофе", "Чай"),
    ("Кино дома или кинотеатр?", "Дома", "Кинотеатр"),
    ("Планировать или импровизировать?", "Планировать", "Импровизировать"),
    ("Писать или звонить?", "Писать", "Звонить"),
    ("Город или природа?", "Город", "Природа"),
    ("Собака или кот?", "Собака", "Кот"),
    ("Вечеринка или тихий вечер?", "Вечеринка", "Тихий вечер"),
    ("Сладкое или солёное?", "Сладкое", "Солёное"),
    ("Путешествие или уютный дом?", "Путешествие", "Дом"),
    ("Спорт или книги?", "Спорт", "Книги"),
    ("Первым написать или ждать?", "Первым", "Ждать"),
    ("Музыка в наушниках или тишина?", "Музыка", "Тишина"),
    ("Лето или зима?", "Лето", "Зима"),
    ("Мемы или длинные разговоры?", "Мемы", "Разговоры"),
    ("Свидание-прогулка или ужин?", "Прогулка", "Ужин"),
    ("Рано вставать или поздно ложиться?", "Рано вставать", "Поздно ложиться"),
    ("Правда в лицо или мягкая подача?", "Правда", "Мягко"),
    ("Приключение или спокойствие?", "Приключение", "Спокойствие"),
]


def today_question() -> dict:
    day = datetime.now(ZoneInfo("Europe/Moscow")).date().toordinal()
    text, a, b = DAILY[day % len(DAILY)]
    return {"text": text, "a": a, "b": b}
