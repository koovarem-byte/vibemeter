"""Фильтр мата, пошлости и оскорблений в анонимных вопросах и ответах.

Ловим по началу слова (с приставками для «еб»), латиницу-двойники и
разделители внутри слова («х.у.й», «xyй»). Список пополнять здесь.
"""

import re

# латиница, похожая на кириллицу
_LOOKALIKE = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м",
    "o": "о", "p": "р", "t": "т", "x": "х", "y": "у", "u": "и", "3": "з",
    "0": "о", "@": "а", "ё": "е",
})

# корни по началу слова
_ROOTS = [
    r"(на|по|о|ни|от|за)?ху[йеёяию]", r"пизд", r"пезд", r"бля", r"сук[аиуе]?\b", r"сучк", r"сучар",
    r"пид[оа]?р", r"педик", r"шлюх", r"шалав", r"проститутк", r"муд[аои]",
    r"г[ао]ндон", r"залуп", r"дроч", r"жоп", r"хер\b", r"херн",
    r"соси\b", r"сосат", r"сосеш", r"отсос", r"минет", r"трах",
    r"порн", r"нюдс", r"сиськ", r"сиси\b", r"пенис", r"вагин",
    r"очк[оау]\b", r"очком\b", r"дебил", r"даун\b", r"урод", r"чмо", r"мраз",
    r"шмар", r"лох\b", r"лошар", r"гнид", r"ублюд", r"выблядок",
]
# «еб» с приставками: заебал, уебок, долбоеб, разъебать…
_EB = r"(за|на|вы|у|от|отъ|до|раз|разъ|по|въ|съ|подъ|про|пере|недо|долбо)?еб"

_PATTERN = re.compile(r"\b(?:" + "|".join(_ROOTS) + r"|" + _EB + r")", re.IGNORECASE)
_LATIN = re.compile(r"\b(fuck|dick|porn|nude|nudes|pussy|bitch|cock)", re.IGNORECASE)


def _normalize(text: str) -> str:
    text = text.lower()
    # разделители внутри слова: х.у.й, х*й → убираем точки и звёздочки между буквами
    text = re.sub(r"(?<=\w)[.*_\-]+(?=\w)", "", text)
    return text.translate(_LOOKALIKE)


def is_bad(text: str) -> bool:
    if not text:
        return False
    if _LATIN.search(text):
        return True
    return bool(_PATTERN.search(_normalize(text)))
