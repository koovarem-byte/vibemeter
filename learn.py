def articles() -> list[dict]:
    """Статьи по порядку: факты high/mid, у которых есть вопрос."""
    return [f for f in facts.for_bot() if f["id"] in QUIZ]


def today_set(read_ids: list[str], read_today: list[str]) -> list[dict]:
    """3 статьи на сегодня: уже открытые сегодня + первые непрочитанные; всё прочитано — по кругу."""
    arts = articles()
    by_id = {a["id"]: a for a in arts}
    out = [by_id[i] for i in read_today if i in by_id][:PER_DAY]
    seen = set(read_ids)
    pool = [a for a in arts if a["id"] not in seen] or arts
    for a in pool:
        if len(out) >= PER_DAY:
            break
        if a not in out:
            out.append(a)
    return out


def quiz_options(fact_id: str, user_id: int) -> list[dict]:
    """Варианты в своём порядке для каждого человека и статьи; idx 0 — правильный."""
    q = QUIZ[fact_id]
    order = [0, 1, 2]
    random.Random(f"{user_id}:{fact_id}").shuffle(order)
    return [{"idx": i, "text": q[1 + i]} for i in order]
